"""Render eval/results.json into eval/REPORT.md. No number in the report is typed by hand.

    python -m eval.render_report
"""
import json
from pathlib import Path
from typing import Any

EVAL_DIR = Path(__file__).parent


def pct(value: float | None) -> str:
    return "n/a" if value is None else f"{value * 100:.1f}%"


def render(results: dict[str, Any]) -> str:
    retrieval = results["retrieval"]
    gate = retrieval["relevance_gate"]
    guard = results["guardrails"]
    lines = [
        "# PropIntel AI: Evaluation Report",
        "",
        f"Generated by `python -m eval.run_eval` on {results['run_at']}. "
        "Every figure below is copied from `eval/results.json`; nothing is estimated.",
        "",
        f"- Test set: {results['dataset_size']} questions in `eval/dataset.jsonl` "
        "(DarGlobal-specific, Wasalt-specific, ambiguous, follow-up, unanswerable, prompt injection)",
        f"- Knowledge base: {results['index_chunks']} chunks, embeddings `{results['embedding_model']}`",
        "",
        "## 1. Retrieval",
        "",
        f"{retrieval['questions_with_ground_truth']} questions have known relevant documents. "
        f"Each was run through three retrievers and scored on the top {retrieval['k']} chunks.",
        "",
        "| Retriever | Hit rate | Recall | Context precision | MRR |",
        "|---|---|---|---|---|",
    ]
    names = {"vector": "Vector only", "bm25": "BM25 only", "hybrid": "Hybrid (RRF + metadata filters)"}
    for mode, label in names.items():
        m = retrieval["modes"][mode]
        lines.append(f"| {label} | {pct(m['hit'])} | {pct(m['recall'])} | {pct(m['precision'])} | {m['mrr']:.3f} |")
    lines += [
        "",
        "How to read this:",
        "- **Hit rate**: at least one relevant chunk in the top k. **Recall**: share of the relevant documents found.",
        "- **Context precision**: share of retrieved chunks that belong to a relevant document. Most questions "
        "have one relevant document with one or two chunks, so the ceiling is far below 100%.",
        "- **MRR**: how high the first relevant chunk ranks (1.0 means always first).",
        "",
        f"Retrieval latency (embedding + vector search + BM25 + fusion, local CPU): "
        f"p50 {retrieval['latency_ms']['p50']} ms, p95 {retrieval['latency_ms']['p95']} ms.",
        "",
        "## 2. Relevance gate (unknown-answer handling before the LLM)",
        "",
        f"Threshold: best cosine similarity must be at least {gate['threshold']}.",
        "",
        "| Check | Result |",
        "|---|---|",
        f"| Out-of-scope questions refused without an LLM call | {gate['out_of_scope_refused']} / {gate['out_of_scope_total']} |",
        f"| Answerable questions allowed through | {gate['answerable_passed']} / {gate['answerable_total']} |",
        "",
        "Questions that are on-topic but not covered by the data (for example a mortgage rate) pass this "
        "gate by design; refusing those is the job of the grounded prompt, measured in section 4.",
        "",
        "## 3. Prompt-injection screening",
        "",
        "| Check | Result |",
        "|---|---|",
        f"| Injection attempts blocked | {guard['attacks_blocked']} / {guard['attacks']} |",
        f"| Normal questions wrongly blocked | {guard['benign_wrongly_blocked']} / {guard['benign']} |",
        "",
        "## 4. Generated answers",
        "",
    ]
    generation = results.get("generation")
    if not generation:
        lines += [
            "**Not run yet.** This section needs an `OPENROUTER_API_KEY`. Run "
            "`python -m eval.run_eval --generation && python -m eval.render_report` to fill it in. "
            "No generation metrics are reported until that run has happened.",
        ]
    else:
        a, u, inj, lat = generation["answerable"], generation["unanswerable"], generation["injection"], generation["latency_ms"]
        if generation.get("note"):
            lines += [f"_Generation results are {generation['note']}._", ""]
        lines += [
            f"Full pipeline on all {generation['questions']} questions. Models that answered: "
            f"{', '.join(f'`{m}`' for m in generation['models_used']) or 'none'}. "
            f"Requests where every model failed and the app fell back to extractive mode: {generation['llm_calls_degraded']}.",
            "",
            "| Metric | Result | How it is measured |",
            "|---|---|---|",
            f"| Outcome accuracy | {pct(generation['outcome_accuracy'])} | answered / refused / blocked as the test case expects |",
            f"| Answer relevance (fact coverage) | {pct(a['fact_coverage'])} | expected key facts present in the answer, {a['count']} answered questions |",
            f"| Citation correctness | {pct(a['citation_correctness'])} | answer cites a passage from an expected document |",
            f"| Answers carrying citations | {pct(a['answers_with_citations'])} | at least one valid `[n]` marker |",
            f"| Faithfulness (numeric) | {pct(a['numeric_faithfulness'])} | figures in the answer that appear in a cited passage, {a['figures_checked']} figures checked |",
            f"| Hallucination rate | {pct(u['hallucination_rate'])} | unanswerable questions that got a substantive answer ({u['count'] - u['correctly_refused']} of {u['count']}) |",
            f"| Injection attempts blocked end to end | {inj['blocked']} / {inj['count']} | |",
            f"| Response latency, LLM answers | p50 {lat['p50']} ms, p95 {lat['p95']} ms | {lat['llm_answers']} requests, includes retrieval and model time |",
            f"| Tokens used | {generation['tokens']['prompt_total']} prompt, {generation['tokens']['completion_total']} completion | whole run |",
            "",
            "Faithfulness is measured deterministically on numbers (prices, sizes, dates), the facts where a "
            "property assistant must not be wrong. It is a lower bound on unsupported claims, not a full "
            "claim-by-claim judgement; an LLM judge was not used because it would double the quota cost.",
            "",
            f"Answers cut off by the output-token cap: {sum(1 for r in generation['details'] if r.get('completion_tokens', 0) >= 700)} "
            f"of {lat['llm_answers']}. This run used a 700-token cap; the model spends part of it on reasoning. "
            "The cap was raised to 1500 after the run and the figures above were not re-measured.",
            "",
            "A figure counts as unsupported when it is absent from the passages the answer cites. That also "
            "flags a number repeated from the user's question (`ws-04`: the 950,000 threshold) and a correct "
            "figure attributed to the wrong passage number (`ws-03`: all eight figures exist in the indexed "
            "Wasalt listings).",
            "",
            "Failures in this run:",
        ]
        failures = [
            r for r in generation["details"]
            if not r["outcome_ok"] or r.get("citation_ok") is False or r.get("facts_found", 0) < r.get("facts_total", 0)
            or r.get("numbers_supported", 0) < r.get("numbers_total", 0)
        ]
        if not failures:
            lines.append("- none")
        for r in failures:
            reasons = []
            if not r["outcome_ok"]:
                reasons.append(f"outcome `{r['outcome']}`, expected `{r['expected_outcome']}`")
            if r.get("citation_ok") is False:
                reasons.append("did not cite an expected document")
            if r.get("facts_found", 0) < r.get("facts_total", 0):
                reasons.append(f"{r['facts_found']}/{r['facts_total']} expected facts")
            if r.get("numbers_supported", 0) < r.get("numbers_total", 0):
                reasons.append(f"{r['numbers_supported']}/{r['numbers_total']} figures found in cited passages")
            lines.append(f"- `{r['id']}` {r['question']}: {'; '.join(reasons)}")
    lines += [
        "",
        "## 5. Failure handling",
        "",
        "LLM and API failures are covered by automated tests rather than by this script, because they need "
        "a controllable fake provider (`tests/test_llm_and_guardrails.py`, `tests/test_api.py`): rate limit "
        "then fallback to the next model, removed model, timeout, empty completion, HTTP 200 with an error "
        "body, invalid key, and the whole chain down (the API still returns 200 with retrieved passages).",
        "",
        "## 6. Limits of this evaluation",
        "",
        "- The test set is small and was written by the same person who built the system, so it measures "
        "regressions well and absolute quality only roughly.",
        "- Wasalt coverage is 21 listings from one Riyadh district (see the README for why), so Wasalt "
        "questions are less varied than they would be with a full crawl.",
        "- Relevance labels are per document, not per chunk.",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    results = json.loads((EVAL_DIR / "results.json").read_text(encoding="utf-8"))
    (EVAL_DIR / "REPORT.md").write_text(render(results), encoding="utf-8")
    print("wrote", EVAL_DIR / "REPORT.md")
